const cases = 'Внедрено 48 роботов на складах ГК «Восток-Сервис» для транспортировки грузов между зонами хранения. В результате производительность выросла вдвое - с 4 до 8 тысяч отгрузок за смену, количество ошибок сократилось в 13 раз.';

const shiftMatch = cases.match(/(\d+\s*(?:тыс|тысяч|т\.?\s*ы\.?\s*с)?)\s*(?:отгруз|операци|посад|груз|ед|короб|посыл|заказ|пallet|паллет)\s*(?:за|в)\s*смен/i);
console.log('Match:', shiftMatch);
if (shiftMatch) {
  let n = shiftMatch[1].replace(/\s/g, '').replace(/\u00A0/g, '');
  n = n.replace(/тыс/g, '000').replace(/тысяч/g, '000').replace(/т\.?\s*ы\.?\s*с/g, '000');
  console.log('Parsed:', parseFloat(n));
}